#!/usr/bin/env python3
"""Generate lib/core/audio/voice_map.g.dart from owner-approved homidev voice jobs.

asset-integrate.sh copies each approved line's OGG into assets/audio/homidev/
(registered). This maps line ids (e.g. aria_ant) to those files, so the app
plays the approved Kokoro line and falls back to the v1 MP3 otherwise.
Mapping source: docs/asset-requests/*/approved-voice.json.

  python3 scripts/gen_voice_map.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
pairs = {}
for f in sorted(ROOT.glob('docs/asset-requests/*/approved-voice.json')):
    for job, line in json.loads(f.read_text()).items():
        path = f'assets/audio/homidev/{job}_voice.ogg'
        assert (ROOT / path).exists(), f'missing {path}'
        pairs[line] = path
body = '\n'.join(f"  '{k}': '{v}'," for k, v in sorted(pairs.items()))
(ROOT / 'lib/core/audio/voice_map.g.dart').write_text(
    "// GENERATED by scripts/gen_voice_map.py - do not edit.\n"
    "// Owner-approved homidev voice lines: line id -> asset.\n\n"
    f"const approvedVoiceLines = <String, String>{{\n{body}\n}};\n")
print(len(pairs), 'voice lines mapped')
